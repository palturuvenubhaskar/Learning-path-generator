"""
Exporter module for the AI Learning Path Generator.
Formats learning roadmaps as Markdown, JSON, and saves to Google Drive via MCP.
"""

import json
from typing import Dict, Any, Optional
from models import LearningRoadmap


class RoadmapExporter:
    """Handles formatting and exporting learning paths across different channels."""

    @staticmethod
    def to_markdown(roadmap: LearningRoadmap) -> str:
        """Converts a LearningRoadmap into clean, professional GitHub-flavored Markdown."""
        lines = []
        lines.append(f"# {roadmap.title}")
        lines.append("")
        lines.append(f"**Target Goal:** {roadmap.goal}  ")
        lines.append(f"**Skill Level:** {roadmap.skill_level}  ")
        lines.append(f"**Total Duration:** {roadmap.total_duration}  ")
        lines.append(f"**Daily Commitment:** {roadmap.daily_commitment}  ")
        if roadmap.created_at:
            lines.append(f"**Generated On:** {roadmap.created_at}  ")
        lines.append("")
        lines.append("---")
        lines.append("")
        lines.append("## Expected Outcome")
        lines.append(roadmap.expected_outcome)
        lines.append("")

        if roadmap.milestones:
            lines.append("## Key Milestones")
            for idx, ms in enumerate(roadmap.milestones, 1):
                lines.append(f"{idx}. {ms}")
            lines.append("")

        lines.append("---")
        lines.append("")
        lines.append("## Day-by-Day Learning Curriculum")
        lines.append("")

        for day in roadmap.days:
            completion_tag = " [Completed]" if day.completed else ""
            lines.append(f"### Day {day.day_number}: {day.topic_title}{completion_tag}")
            lines.append(f"- **Estimated Time:** {day.estimated_time}")
            lines.append("")
            lines.append("#### Concept Explanation")
            lines.append(day.concept_explanation)
            lines.append("")
            
            if day.key_takeaways:
                lines.append("#### Key Takeaways")
                for item in day.key_takeaways:
                    lines.append(f"- {item}")
                lines.append("")

            if day.resources:
                lines.append("#### Recommended Learning Resources")
                for res in day.resources:
                    verified_tag = " `[MCP Verified]`" if res.is_mcp_verified else ""
                    author = f" by *{res.channel_or_author}*" if res.channel_or_author else ""
                    lines.append(f"- [{res.title}]({res.url}) ({res.platform}){author}{verified_tag}")
                    if res.relevance_note:
                        lines.append(f"  > *Note: {res.relevance_note}*")
                lines.append("")

            if day.practice_exercises:
                lines.append("#### Hands-on Practice Exercises")
                for ex in day.practice_exercises:
                    lines.append(f"- [ ] {ex}")
                lines.append("")

            if day.assignment:
                lines.append("#### Daily Assignment")
                lines.append(f"> {day.assignment}")
                lines.append("")

            if day.revision_checkpoint:
                lines.append("#### Revision & Self-Assessment")
                lines.append(f"> {day.revision_checkpoint}")
                lines.append("")

            lines.append("---")
            lines.append("")

        if roadmap.capstone_project:
            lines.append("## Final Capstone Project")
            lines.append(f"### {roadmap.capstone_project.title}")
            lines.append(roadmap.capstone_project.description)
            lines.append("")
            if roadmap.capstone_project.deliverables:
                lines.append("**Deliverables & Evaluation Criteria:**")
                for deliv in roadmap.capstone_project.deliverables:
                    lines.append(f"- {deliv}")
                lines.append("")

        if roadmap.next_steps:
            lines.append("## Next Steps & Further Study")
            for ns in roadmap.next_steps:
                lines.append(f"- {ns}")
            lines.append("")

        lines.append("---")
        lines.append("*Generated by Learning Path Generator (Model Context Protocol • MCP)*")
        return "\n".join(lines)

    @staticmethod
    def to_json(roadmap: LearningRoadmap) -> str:
        """Serializes roadmap to formatted JSON string."""
        return roadmap.model_dump_json(indent=2)

    @classmethod
    async def save_to_google_drive_mcp(
        cls,
        roadmap: LearningRoadmap,
        drive_mcp_url: str
    ) -> Dict[str, Any]:
        """
        Saves the roadmap to Google Drive using the connected Pipedream Google Drive MCP server.
        """
        if not drive_mcp_url or not drive_mcp_url.strip():
            return {
                "success": False,
                "message": "Google Drive MCP URL is not configured. Please provide a valid Pipedream Drive endpoint."
            }

        markdown_content = cls.to_markdown(roadmap)
        filename = f"{roadmap.title.replace(' ', '_')}_Roadmap.md"

        try:
            from mcp_client import MCPManager
            tools = await MCPManager.get_all_configured_tools(drive_url=drive_mcp_url)
            
            # Find an appropriate file creation tool
            create_tool = None
            for tool in tools:
                tool_name = getattr(tool, "name", "").lower()
                if "create" in tool_name or "upload" in tool_name or "write" in tool_name:
                    create_tool = tool
                    break

            if not create_tool and tools:
                create_tool = tools[0]

            if create_tool:
                result = await create_tool.ainvoke({
                    "name": filename,
                    "content": markdown_content
                })
                return {
                    "success": True,
                    "message": f"Successfully saved to Google Drive via MCP tool: {getattr(create_tool, 'name', 'drive_tool')}",
                    "result": str(result)
                }
            else:
                return {
                    "success": False,
                    "message": "Connected to Google Drive MCP server, but no file upload tool was detected."
                }
        except Exception as err:
            return {
                "success": False,
                "message": f"Failed to save to Google Drive via MCP: {str(err)}"
            }
